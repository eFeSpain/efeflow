/* Model → nftables source. Tables are discovered, never assumed. */
import { MODEL, ruleLine } from './model.js';
import { PROJECT } from './project.js';
export function generate(){
  const L = [];
  L.push("#!/usr/sbin/nft -f");
  L.push(`# ${PROJECT()} — generated by eFeFlow · round-trip safe`);
  L.push("");
  L.push("flush ruleset");
  L.push("");

  const tables = [...new Set([
    ...MODEL.chains.map(c=>c.table),
    ...MODEL.sets.map(s=>s.table).filter(Boolean),
  ])];
  if(!tables.length) tables.push("inet fw");

  tables.forEach(tb=>{
    L.push(`table ${tb} {`);
    /* a set with no recorded table belongs to the first one, as nft requires
       it to live beside the rules that reference it */
    MODEL.sets.filter(s=>(s.table||tables[0])===tb).forEach(s=>{
      L.push(`\t${s.kind==="map"?"map":"set"} ${s.n} {`);
      L.push(`\t\ttype ${s.t}${s.f?" ; flags "+s.f:""}`);
      if(s.el.length) L.push(`\t\telements = { ${s.el.join(", ")} }`);
      L.push("\t}");
      L.push("");
    });
    MODEL.chains.filter(c=>c.table===tb).forEach(ch=>{
      L.push(`\tchain ${ch.id} {`);
      if(ch.hook)
        L.push(`\t\ttype ${ch.type} hook ${ch.hook} priority ${ch.prio} ; policy ${ch.policy} ;`);
      ch.rules.forEach(r=>{
        if(!r.on) return;
        L.push(`\t\t${ruleLine(r)}${r.cmt?` comment "${r.cmt}"`:""}`);
      });
      L.push("\t}");
      L.push("");
    });
    if(L.at(-1)==="") L.pop();
    L.push("}");
    L.push("");
  });
  if(L.at(-1)==="") L.pop();
  return L;
}
